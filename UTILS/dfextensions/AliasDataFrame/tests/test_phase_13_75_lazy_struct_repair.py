sys.path.insert(0, os.path.dirname(HERE))          # ADF sources
from AliasDataFrame import AliasDataFrame          # noqa: E402
from LazyTreeReader import LazyTreeReader          # noqa: E402

CLEAN = os.path.join(HERE, "lazy_struct_fixture_clean.root")
HAZARD = os.path.join(HERE, "lazy_struct_fixture_hazard.root")
CHAIN = [os.path.join(HERE, "chain_part1.root"), os.path.join(HERE, "chain_part2.root")]

@pytest.fixture(autouse=True)
def _fixtures_present():
    """Generate fixtures on first use. Robust to pytest rootdir differences
    (tests/ not on sys.path) and xdist parallel workers (exclusive lockfile;
    losers wait for the winner's files). Pre-generating once with
    `python tests/make_fixtures.py` from inside tests/ also works and skips
    all of this."""
    if os.path.exists(CLEAN):
        return
    if HERE not in sys.path:
        sys.path.insert(0, HERE)
    lock = os.path.join(HERE, ".fixtures.lock")
    import time
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        for _ in range(600):                      # another worker is generating
            if os.path.exists(CLEAN) and os.path.exists(HAZARD)                and all(os.path.exists(p) for p in CHAIN):
                return
            time.sleep(0.1)
        raise RuntimeError("fixture generation by peer worker timed out")
    try:
        from make_fixtures import make_all
        make_all(HERE)
    finally:
        os.close(fd)
        os.unlink(lock)

def fresh(path=CLEAN):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return AliasDataFrame.read_tree_lazy(path, "tree")

def oracle(path, branch):
    return uproot.open(path)["tree"][branch].array(library="np")


# ────────────────────────── Stage 1: reader classification ──────────────────────────
class TestStage1_ReaderClassification:
    EXPECT = {"dedxTPC/dEdxMaxTPC": True, "dedxTPC/clusterQ": False,
              "ndedxTPC/clusterQ": True, "mTOFLength/len": True,
              "jag": False, "njag": True, "mult": True, "decoyUnused": True}

    def test_tree_reader_three_valued(self):
        r = LazyTreeReader(CLEAN, "tree")
        for k, want in self.EXPECT.items():
            assert r.is_scalar_branch(k) is want, k
        assert r.is_scalar_branch("NOT_A_BRANCH") is None      # UNKNOWN, never bool

    def test_chain_reader_delegates(self):
        adf = AliasDataFrame.read_chain_lazy(CHAIN, "tree")
        r = adf._lazy_reader
        assert r.is_scalar_branch("dedxTPC/dEdxMaxTPC") is True
        assert r.is_scalar_branch("jag") is False
        assert r.is_scalar_branch("NOT_A_BRANCH") is None


# ────────────────────────── Stage 2: detector policy ──────────────────────────
class TestStage2_DetectorPolicy:
    def test_clean_registration_and_provenance(self):
        adf = fresh()
        assert set(adf._structs) == {"dedxTPC", "mTOFLength"}
        assert all(v["origin"] == "auto" for v in adf._structs.values())
        assert "clusterQ" not in adf._structs["dedxTPC"]["members"]      # H1

    def test_h2_count_helper_never_a_struct(self):
        adf = fresh()
        assert "ndedxTPC" not in adf._structs

    def test_h3_collision_blocks_auto_member(self):
        adf = fresh(HAZARD)
        assert "dEdxMaxTPC" not in adf._structs.get("dedxTPC", {}).get("members", [])
        # the untouched members still register
        assert "dEdxTotTPC" in adf._structs["dedxTPC"]["members"]

    def test_c1_unknown_never_scalar(self):
        adf = fresh()
        class NoChecker:                                   # reader without classifier
            available_branches = {"mys/a"}
        adf2 = AliasDataFrame(pd.DataFrame({"x": [1.0]}))
        adf2._lazy_reader = NoChecker()
        with warnings.catch_warnings(record=True) as w:
            warnings.simplefilter("always")
            det = adf2.detect_structs(register=True)
        assert det == {} and "mys" not in adf2._structs
        assert any("UNKNOWN" in str(x.message) for x in w)

    def test_explicit_register_precedence_survives(self):   # T-AUTO-5 half
        adf = fresh()
        adf.register_struct("myExplicit", ["m1"])
        assert adf._structs["myExplicit"]["origin"] == "explicit"
        adf.refresh_structs()                               # must not clobber
        assert adf._structs["myExplicit"]["origin"] == "explicit"


# ────────────────────────── Stage 3: lifecycle ──────────────────────────
class TestStage3_Lifecycle:
    def test_auto_at_tree_construction(self):               # T-AUTO-1 registration half
        adf = fresh()
        assert "dedxTPC" in adf._structs                    # no manual refresh anywhere

    def test_auto_at_chain_construction(self):              # T-AUTO-2 registration half
        adf = AliasDataFrame.read_chain_lazy(CHAIN, "tree")
        assert "dedxTPC" in adf._structs

    def test_idempotence(self):                             # T-AUTO-4
        adf = fresh()
        snap = {k: dict(v, l2i=dict(v["l2i"])) for k, v in adf._structs.items()}
        adf._ensure_struct_catalog(); adf.refresh_structs(); adf.eval("dedxTPC.dEdxMaxTPC")
        adf._ensure_struct_catalog()
        assert set(adf._structs) == set(snap)
        for k in snap:
            assert adf._structs[k]["members"] == snap[k]["members"]
            assert adf._structs[k]["l2i"] == snap[k]["l2i"]

    def test_fp_cache_prevents_rescan(self):                # C-no-repeated-scan
        adf = fresh()
        calls = {"n": 0}
        orig = adf.detect_structs
        adf.detect_structs = lambda register=True: (calls.__setitem__("n", calls["n"]+1) or orig(register))
        for _ in range(5):
            adf._ensure_struct_catalog()
        assert calls["n"] == 0                              # fp unchanged -> no rescan

    def test_eager_noop(self):                              # T-DRAW-10 half
        adf = AliasDataFrame(pd.DataFrame({"x": [1.0, 2.0]}))
        adf._ensure_struct_catalog()
        assert adf._structs == {}

    def test_tree_initial_branches_normalized(self):        # D4 constructor ordering
        adf = AliasDataFrame.read_tree_lazy(CLEAN, "tree",
                                            branches=["dedxTPC/dEdxMaxTPC", "mult"])
        assert "dEdxMaxTPC__dedxTPC" in adf.df.columns      # physical -> internal
        assert "dedxTPC/dEdxMaxTPC" not in adf.df.columns


