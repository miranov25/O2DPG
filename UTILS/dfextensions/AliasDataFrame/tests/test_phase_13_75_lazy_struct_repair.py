# ────────────────────────── Stage 5: rewrite + eval ──────────────────────────
@pytest.mark.invariance
class TestStage5_RewriteEval:
    def test_dot_eval_equals_physical_oracle(self):         # T-AUTO-1 + invariance 1
        adf = fresh()
        r = adf.eval("dedxTPC.dEdxMaxTPC")
        assert np.array_equal(r.to_numpy(), oracle(CLEAN, "dedxTPC/dEdxMaxTPC"))

    def test_dot_eval_equals_internal_column(self):         # invariance 2
        adf = fresh()
        r = adf.eval("dedxTPC.dEdxMaxTPC")
        assert np.array_equal(r.to_numpy(), adf.df["dEdxMaxTPC__dedxTPC"].to_numpy())

    def test_alias_over_struct_equals_direct(self):         # T-AUTO-3 + invariance 3
        adf = fresh()
        adf.add_alias("dedx_ratio", "dedxTPC.dEdxMaxTPC/dedxTPC.dEdxTotTPC")
        got = adf.eval("dedx_ratio").to_numpy()
        want = (oracle(CLEAN, "dedxTPC/dEdxMaxTPC")
                / oracle(CLEAN, "dedxTPC/dEdxTotTPC"))
        assert np.max(np.abs(got - want)) == 0.0

    def test_tree_equals_chain(self):                       # invariance 5 (same file both ways)
        a1 = fresh(CHAIN[0])
        a2 = AliasDataFrame.read_chain_lazy([CHAIN[0]], "tree")
        v1 = a1.eval("dedxTPC.dEdxMaxTPC").to_numpy()
        v2 = a2.eval("dedxTPC.dEdxMaxTPC").to_numpy()
        assert np.array_equal(v1, v2)

    def test_auto_equals_explicit_registration(self):       # invariance 6
        auto = fresh()
        va = auto.eval("dedxTPC.dEdxMaxTPC").to_numpy()
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            man = AliasDataFrame.read_tree_lazy(CLEAN, "tree")
        # wipe auto catalog, register explicitly, compare
        man._structs.clear(); man._struct_catalog_fp = ("locked",)      # block re-auto
        man.register_struct("dedxTPC", ["dEdxMaxTPC", "dEdxTotTPC", "dEdxMaxIROC"])
        vm = man.eval("dedxTPC.dEdxMaxTPC").to_numpy()
        assert np.array_equal(va, vm)

    def test_builtin_named_member(self):                    # mTOFLength.len stress
        adf = fresh()
        r = adf.eval("mTOFLength.len")
        assert np.array_equal(r.to_numpy(), oracle(CLEAN, "mTOFLength/len"))


